local source = assert(loadfile('Mods/HearYourFriends/Scripts/state.lua'), 'state module missing')
local state = source().new({gain=1,soloTest=false})
state:sync({{key='a',name='Alice'},{key='b',name='Bob'}})
state:setMaster(2); state:setPlayer('a',.5)
assert(state:effective('a')==1 and state:effective('b')==2, 'master multiplies each player level')
state:setPlayer('a',0)
assert(state:effective('a')==0 and state:effective('b')==2, 'one player can be silent')
state:setMaster(4);state:setPlayer('b',4)
assert(state:effective('b')==16, 'combined gain is explicit, not silently clipped to four')
state:setMaster(100);state:setPlayer('b',-2)
assert(state.master==4 and state:effective('b')==0, 'each slider is bounded to zero through four')
state:setPlayer('b',2);state:sync({{key='a',name='Alice'}})
state:sync({{key='b',name='New Bob'}})
assert(state:effective('b')==4, 'disconnected player overrides cannot leak to a new row')
state:setMaster(0/0)
assert(state.master==4, 'rejects nonfinite inputs')
print('player level tests passed')
